#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
from statistics import mean
from typing import Any


def main() -> int:
    args = parse_args()
    variants = [parse_variant(item) for item in args.variant]
    rows = [summarize_variant(label, p010, p014) for label, p010, p014 in variants]
    anchor = rows[0]["mean_hv"] if rows else None
    for row in rows:
        row["delta_mean_hv"] = row["mean_hv"] - anchor if anchor is not None else None
    out_json = Path(args.out_json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    write_tex(Path(args.out_tex), rows)
    print(json.dumps(rows, ensure_ascii=False, indent=2))
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Export matched P010/P014 current-code ablation rows for the main paper."
    )
    parser.add_argument(
        "--variant",
        action="append",
        required=True,
        help="LABEL=P010_RUN_DIR,P014_RUN_DIR; the first variant is the delta anchor.",
    )
    parser.add_argument("--out-json", required=True)
    parser.add_argument("--out-tex", required=True)
    return parser.parse_args()


def parse_variant(value: str) -> tuple[str, Path, Path]:
    if "=" not in value or "," not in value:
        raise ValueError(f"expected LABEL=P010_RUN_DIR,P014_RUN_DIR, got {value!r}")
    label, paths = value.split("=", 1)
    p010, p014 = paths.split(",", 1)
    return label.strip(), Path(p010.strip()), Path(p014.strip())


def summarize_variant(label: str, p010_dir: Path, p014_dir: Path) -> dict[str, Any]:
    p010 = summarize_episode(p010_dir, "NLDO-P010")
    p014 = summarize_episode(p014_dir, "NLDO-P014")
    return {
        "label": label,
        "p010_hv": p010["hv"],
        "p014_hv": p014["hv"],
        "mean_hv": mean([p010["hv"], p014["hv"]]),
        "solved_states": p010["solved_states"] + p014["solved_states"],
        "total_states": p010["total_states"] + p014["total_states"],
        "p010_run_dir": str(p010_dir),
        "p014_run_dir": str(p014_dir),
    }


def summarize_episode(run_dir: Path, expected_episode: str) -> dict[str, Any]:
    path = run_dir / "reference_metrics" / "reference_stage_metrics.csv"
    if not path.exists():
        raise FileNotFoundError(path)
    with path.open(newline="", encoding="utf-8") as handle:
        rows = [
            row
            for row in csv.DictReader(handle)
            if str(row.get("episode_id") or "") == expected_episode
            and int(float(row.get("stage_index") or 0)) > 0
        ]
    if not rows:
        raise ValueError(f"no dynamic rows for {expected_episode} in {path}")
    values = [float(row["normalized_hv"]) for row in rows if finite(row.get("normalized_hv"))]
    states: dict[int, list[dict[str, str]]] = {}
    for row in rows:
        states.setdefault(int(float(row["stage_index"])), []).append(row)
    solved = sum(
        1
        for state_rows in states.values()
        if any(str(row.get("feasible") or "").lower() in {"1", "true", "yes"} for row in state_rows)
    )
    return {"hv": mean(values), "solved_states": solved, "total_states": len(states)}


def finite(value: Any) -> bool:
    try:
        return math.isfinite(float(value))
    except (TypeError, ValueError):
        return False


def write_tex(path: Path, rows: list[dict[str, Any]]) -> None:
    lines = [
        "% Auto-generated by scripts/experiments/export_liveopt_representative_ablation_rows.py.",
        r"\newcommand{\LiveOptComponentAblationRows}{%",
    ]
    for index, row in enumerate(rows):
        delta = "--" if index == 0 else f"{row['delta_mean_hv']:+.3f}"
        prefix = r"\rowcolor{LiveOptRowAccent}" if index == 0 else ""
        if prefix:
            lines.append(prefix)
        lines.append(
            f"{escape_tex(row['label'])} & {row['solved_states']}/{row['total_states']} & "
            f"{row['p010_hv']:.3f} & {row['p014_hv']:.3f} & {row['mean_hv']:.3f} & {delta} \\\\"
        )
    lines.append("}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def escape_tex(value: str) -> str:
    return value.replace("_", r"\_").replace("w/o", r"w/o")


if __name__ == "__main__":
    raise SystemExit(main())
